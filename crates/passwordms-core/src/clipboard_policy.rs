//! 剪贴板自动清空策略（D-135）。
//!
//! 密码 / TOTP 这类敏感文本复制后要在 TTL 到期时清空（F-06 / A-03）；用户名、配对码
//! 这类非敏感文本**不该被清**——用户经常是先复制、过一会儿才去粘贴。
//!
//! 界面用「传 `0` 表示不做自动清空」表达后者。这个约定必须由后端**显式兑现**：
//! 原实现把 `0` 直接丢进 `Duration::from_secs(0)`，等效于「写完立刻清」，于是
//! 「复制用户名」的现象是 toast 报「已复制」而剪贴板是空的（必现，不是竞态）。
//!
//! 策略放这里而不是外壳层，是为了能被 `cargo test -p passwordms-core` 直接钉住
//! ——命令层（`src-tauri`）在本机无法作为测试目标链接（cdylib 导出序号溢出）。

/// 「不做自动清空」的 TTL 约定值。
///
/// 前端复制非敏感文本时传它，后端据此**不安排**任何清理线程。
pub const NO_AUTO_CLEAR_SECS: u16 = 0;

/// 依据 TTL 算出兜底清理应当等待的秒数。
///
/// - [`NO_AUTO_CLEAR_SECS`]（0）→ `None`：**不安排清理**；
/// - 其余 → `Some(ttl)`：到期清空（仅当剪贴板仍是本应用写的那份，见 A-03）。
///
/// 返回 `Option<u64>` 而不是 `Duration`：这里是**策略**，是否需要计时、用什么时钟
/// 由外壳决定（桌面端开线程睡眠，移动端可换成任务调度）。
pub fn auto_clear_delay_secs(ttl_secs: u16) -> Option<u64> {
    if ttl_secs == NO_AUTO_CLEAR_SECS {
        None
    } else {
        Some(u64::from(ttl_secs))
    }
}
